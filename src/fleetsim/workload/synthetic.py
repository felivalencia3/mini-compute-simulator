"""Synthetic per-class workload generation (DESIGN 5.1, traffic-math §2/§3).

:class:`SyntheticSource` implements the
:class:`~fleetsim.workload.base.JobSource` pull protocol: per workload
class it runs an independent arrival process (poisson | nhpp | mmpp2 |
hawkes — see ARRIVAL PROCESSES below), samples sizes/durations/tenants/
outcomes from named RNG streams, quantizes chip counts against the
fleet's node size, and merges all classes into one time-ordered stream
via a lazy heap.  Classes with ``arrival: backlog[target_pending=N]``
(v0.2) are CLOSED-LOOP instead: they emit nothing through
``next_arrival`` and are topped up to N pending jobs by the
engine-driven :meth:`SyntheticSource.refill` hook at every scheduler
wake — one source object covers both kinds.

UNITS: arrival times int microseconds since sim epoch; every ``*_s``
quantity float seconds.  Duration DistSpec params are **int microseconds**
(the config storage rule) — write them with unit suffixes
(``lognormal[median=2m, p90=30m]``); a bare number in a duration
expression is microseconds, NOT seconds.

ARRIVAL PROCESSES (traffic-math §2.1/§3; all draw only from the class's
``arrivals/<class>`` stream, in a pinned order):

- :class:`PoissonArrivals` — homogeneous; one exponential gap per event.
- :class:`NHPPArrivals` — Lewis-Shedler thinning against a rate curve
  (one exponential + one uniform per CANDIDATE); the curve is either the
  pinned v0.1 step curve (``seasonality: v01_steps`` — byte-identical to
  v0.1 ``diurnal: true``) or a log-linear harmonic
  :class:`HarmonicCurve` whose ``theta0`` normalization keeps the
  configured rate the mean.
- :class:`MMPP2Arrivals` — 2-state CTMC-modulated Poisson; per regime
  sojourn: one exponential (sojourn), one poisson (count), one
  ``uniform(size=n)`` (times), and — only with a seasonal envelope — one
  ``random(size=n)`` (thinning accepts).
- :class:`HawkesArrivals` — Ogata thinning with an exponential kernel
  (one exponential + one uniform per candidate); ``branching`` is the
  mean number of children per event (stationary iff < 1) and the NHPP
  baseline is derived as ``mu(t) = (1-branching) * lambda_c(t)``.

RNG STREAMS (the determinism contract; all derived from the shared
:class:`~fleetsim.engine.rng.RngStreams`):

- ``arrivals/<class>``: ALL arrival randomness, in the fixed per-process
  order above (gaps, thinning accepts, regime sojourns/counts, Hawkes
  accept draws).
- ``size/<class>``: one draw per job (chip count, pre-quantization).
- ``duration/<class>``: two draws per job — the true duration, then the
  walltime-overestimate factor (lognormal median 1.5, p90 3); THREE with
  a splice duration (branch + inversion + walltime factor).
- ``tenant/<class>``: one uniform per job (finite bounded Zipf over
  ``n_tenants`` with exponent ``tenant_zipf_s``, default 1.2 —
  traffic-math §2.4; tenants ``t0..t{n-1}``, ``t0`` dominant).
- ``outcome/<class>``: one uniform per job; jobs that abort
  (probability ``abort_prob``) draw two more — the FAILED(80%) /
  CANCELED(20%) split, then the early-truncation fraction ``U(0,1)^2``
  (failures skew early, DESIGN 5.1).

DIURNAL STEP CURVE (pinned, v0.1 compatible): multiplier 0.5 in
[00:00, 06:00), 0.8 in [12:00, 13:00) and [18:00, 19:00), else 1.0;
day = 86400 s.  Every curve is normalized so the configured rate is the
MEAN rate; arrivals are generated by thinning a homogeneous process at
the curve's peak-bound rate.

QUANTIZATION (DESIGN 4.1): a sampled size below the node size rounds UP
to the next power of two (becoming one whole node if that reaches the
node size); at/above the node size it rounds UP to a whole-node multiple.
Node size = max leaf chip count for the class's chip type (all leaves
when the fleet is heterogeneous and the type is unpinned).

INVARIANTS
----------
- Emitted ``(time_us, job)`` pairs are non-decreasing in time; times are
  strictly below the horizon; the source keeps returning ``None`` after
  exhaustion.
- Per class, draws happen in arrival order with the fixed per-stream
  counts above, so a run is a pure function of (config, fleet, seed).
- Jobs are plain declarative :class:`~fleetsim.model.Job` objects
  (:class:`SyntheticJob` adds only ``terminal_status_override``); one
  gang each, fresh ``Constraint`` per job (never shared with config).
"""

