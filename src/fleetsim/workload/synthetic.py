#: Walltime-overestimate factor applied to the sampled true duration to
#: produce the scheduler-visible ``walltime_est_s`` (median 1.5x, p90 3x —
#: users overestimate; ~23% of draws are < 1, i.e. underestimates).
_WALLTIME_FACTOR = LogNormal(1.5, 3.0)

#: Mean of the pinned diurnal multiplier curve over one day
#: ((6h * 0.5 + 2h * 0.8 + 16h * 1.0) / 24h).
DIURNAL_MEAN = (6 * 0.5 + 2 * 0.8 + 16 * 1.0) / 24.0


def diurnal_multiplier(t_us: int) -> float:
    """The pinned diurnal rate multiplier at sim time ``t_us``.

    0.5 in [00:00, 06:00), 0.8 in [12:00, 13:00) and [18:00, 19:00),
    else 1.0 (night trough plus 12pm/6pm dips, per Helios).  The sim
    epoch is midnight.
    """
    hour = (t_us % DAY) / HOUR
    if hour < 6.0:
        return 0.5
    if 12.0 <= hour < 13.0 or 18.0 <= hour < 19.0:
        return 0.8
    return 1.0


def quantize_chips(raw: float, node_size: int, segment_nodes: int = 1) -> int:
    """Quantize a sampled chip count per DESIGN 4.1.

    ``raw`` is first ceiled to an int of at least 1.  Below ``node_size``
    it rounds UP to the next power of two (one whole node if that meets or
    exceeds the node size); at/above ``node_size`` it rounds UP to a
    whole-node multiple.  With ``segment_nodes > 1`` (segmented classes,
    v0.2) every draw instead rounds UP to a multiple of the SEGMENT
    quantum ``node_size * segment_nodes`` — segmented gangs are
    whole-node only and must divide into equal segments.  Raises
    ``ValueError`` on non-finite ``raw``, ``node_size < 1`` or
    ``segment_nodes < 1``.
    """
    if node_size < 1:
        raise ValueError(f"node_size must be >= 1, got {node_size}")
    if segment_nodes < 1:
        raise ValueError(f"segment_nodes must be >= 1, got {segment_nodes}")
    if not math.isfinite(raw):
        raise ValueError(f"sampled chip count must be finite, got {raw!r}")
    c = max(1, math.ceil(raw))
    if segment_nodes > 1:
        quantum = node_size * segment_nodes
        return quantum * -(-c // quantum)
    if c >= node_size:
        return node_size * -(-c // node_size)
    p = 1 << (c - 1).bit_length()  # next power of two >= c
    return p if p < node_size else node_size


def node_sizes(fleet: FleetTree) -> dict[str, int]:
    """Node size (max leaf chip count) per chip type, sorted by type.

    Raises ``ValueError`` if the fleet has no leaves.
    """
    out: dict[str, int] = {}
    for lid in fleet.leaves():
        leaf = fleet.domain(lid)
        out[leaf.chip_type] = max(out.get(leaf.chip_type, 0), leaf.chips)
    if not out:
        raise ValueError("fleet has no leaf nodes")
    return dict(sorted(out.items()))


def bounded_zipf_cdf(n: int, s: float) -> list[float]:
    """CDF of the FINITE Zipf pmf ``p_i ∝ (i+1)^-s`` over ranks
    ``0..n-1`` (traffic-math §2.4 — never ``rng.zipf``, which samples
    the unbounded Zeta distribution).  ``s == 0`` degenerates to
    uniform.  Returns ``n`` cumulative values with the last pinned to
    exactly 1.0.  Raises ``ValueError`` for ``n < 1`` or ``s < 0``.
    """
    if n < 1:
        raise ValueError(f"bounded_zipf_cdf requires n >= 1, got {n}")
    if s < 0:
        raise ValueError(f"bounded_zipf_cdf requires s >= 0, got {s}")
    weights = [(i + 1) ** -s for i in range(n)]
    total = sum(weights)
    cum: list[float] = []
    acc = 0.0
    for w in weights:
        acc += w / total
        cum.append(acc)
    cum[-1] = 1.0  # guard float accumulation
    return cum


